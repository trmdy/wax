#[test]
fn malformed_style_attributes_keep_formats_and_valid_neighbor_styles() {
    let malformed = include_str!("fixtures/reader-src/xl/styles.xml")
        .replace(r#"rgb="FF1A2B3C""#, r#"rgb="not-a-color""#);
    let fixture = fixture_with_replaced_part("xl/styles.xml", malformed.as_bytes());
    let document = read_with_deadline(CalamineReader, fixture.path(), ReaderOptions::default());

    assert!(document.ok, "{:?}", document.error);
    assert!(!document
        .warnings
        .iter()
        .any(|warning| warning.contains("xlsx styles could not be read")));

    let cells = &document.sheets[0].cells;
    assert_eq!(cell(cells, 0, 3).fmt.as_deref(), Some("yyyy-mm-dd"));
    assert_eq!(cell(cells, 0, 4).fmt.as_deref(), Some("mm-dd-yy"));
    assert_eq!(cell(cells, 0, 3).s, Some(0));
    assert_eq!(cell(cells, 0, 4).s, Some(0));
    assert_eq!(cell(cells, 0, 6).s, Some(1));
    assert_eq!(
        document.styles,
        [
            CellStyle {
                fill_color: Some("#EEDDCC".to_owned()),
                ..CellStyle::default()
            },
            CellStyle {
                font_color: Some("#969696".to_owned()),
                fill_color: Some("#9999FF".to_owned()),
                ..CellStyle::default()
            }
        ]
    );
}

#[test]
fn malformed_column_declarations_degrade_without_losing_styles() {
    let malformed = include_str!("fixtures/reader-src/xl/worksheets/sheet1.xml")
        .replace(r#"customWidth="true""#, r#"customWidth="maybe""#);
    let fixture = fixture_with_replaced_part("xl/worksheets/sheet1.xml", malformed.as_bytes());
    let document = read_with_deadline(CalamineReader, fixture.path(), ReaderOptions::default());

    assert!(document.ok, "{:?}", document.error);
    assert!(document
        .warnings
        .iter()
        .any(|warning| warning.contains("xlsx column widths")));
    assert!(document.sheets[0].col_infos.is_empty());
    assert!(!document.styles.is_empty());
}

#[test]
fn display_strings_are_delegated_to_wax_fmt_with_raw_values() {
    let document = CalamineReader.read(&fixture("reader.xlsx"), ReaderOptions::default());
    let cells = &document.sheets[0].cells;

    assert_eq!(
        cell(cells, 0, 0).d,
        render("General", FmtValue::Text("Hello shared"), true)
    );
    assert_eq!(
        cell(cells, 0, 1).d,
        render("General", FmtValue::Bool(true), true)
    );
    assert_eq!(
        cell(cells, 0, 2).d,
        render("General", FmtValue::Error("#DIV/0!"), true)
    );
    assert_eq!(
        cell(cells, 0, 3).d,
        render("yyyy-mm-dd", FmtValue::Number(0.0), true)
    );
    assert_eq!(
        cell(cells, 0, 4).d,
        render("mm-dd-yy", FmtValue::Number(1.0), true)
    );
    assert_eq!(
        cell(cells, 1, 2).d,
        render("General", FmtValue::Number(5.0), true)
    );
    assert_eq!(
        cell(cells, 1, 6).d,
        render("0.0000 \"widgets\"", FmtValue::Number(12.3456), true)
    );
}

