#[test]
#[ignore = "requires the machine-local corpus payload via WAX_CORPUS_ROOT"]
fn corpus_spot_check_extracts_styles_and_widths_from_xlsx_and_xlsm() {
    let root = PathBuf::from(
        std::env::var("WAX_CORPUS_ROOT").expect("WAX_CORPUS_ROOT must point to corpus/files"),
    );
    let paths = [
        "poi/test-data/spreadsheet/63934.xlsx",
        "poi/test-data/spreadsheet/simple-monthly-budget.xlsx",
        "poi/test-data/spreadsheet/60512.xlsm",
    ];
    let mut styled_cells = 0;
    let mut widths = 0;
    for relative in paths {
        let document = CalamineReader.read(&root.join(relative), ReaderOptions::default());
        assert!(document.ok, "{relative}: {:?}", document.error);
        assert!(!document.styles.is_empty(), "{relative}: no styles");
        styled_cells += document
            .sheets
            .iter()
            .flat_map(|sheet| &sheet.cells)
            .filter(|cell| cell.s.is_some())
            .count();
        widths += document
            .sheets
            .iter()
            .map(|sheet| sheet.col_infos.len())
            .sum::<usize>();
    }
    assert!(styled_cells > 0);
    assert!(widths > 0);
}
