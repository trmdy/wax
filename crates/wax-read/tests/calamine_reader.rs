use tempfile::NamedTempFile;
use wax_core::{Cell, CellStyle, CellType, CellValue, ColInfo};
use wax_fmt::{render, FmtValue};
use wax_read::{read_with_deadline, CalamineReader, Reader, ReaderOptions};
use zip::write::SimpleFileOptions;
use zip::{ZipArchive, ZipWriter};

fn fixture(name: &str) -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("tests")
        .join("fixtures")
        .join(name)
}

fn cell(cells: &[Cell], row: u32, col: u32) -> &Cell {
    cells
        .iter()
        .find(|cell| (cell.r, cell.c) == (row, col))
        .expect("fixture cell should be present")
}

fn fixture_with_replaced_part(part: &str, replacement: &[u8]) -> NamedTempFile {
    let source = File::open(fixture("reader.xlsx")).expect("reader fixture should open");
    let mut source = ZipArchive::new(source).expect("reader fixture should be a zip");
    let output = tempfile::Builder::new()
        .suffix(".xlsx")
        .tempfile()
        .expect("temporary fixture should be created");
    let mut archive = ZipWriter::new(output.reopen().expect("temporary fixture should reopen"));
    for index in 0..source.len() {
        let mut entry = source.by_index(index).expect("fixture entry should open");
        if entry.is_dir() {
            continue;
        }
        let mut bytes = Vec::new();
        entry
            .read_to_end(&mut bytes)
            .expect("fixture entry should read");
        archive
            .start_file(entry.name(), SimpleFileOptions::default())
            .expect("temporary fixture entry should start");
        archive
            .write_all(if entry.name() == part {
                replacement
            } else {
                &bytes
            })
            .expect("temporary fixture entry should write");
    }
    archive.finish().expect("temporary fixture should finish");
    output
}

// reader.xlsx is a hand-authored minimal OOXML package generated by the
// adjacent generate-reader-fixture.sh script. It intentionally combines
// shared strings, formulas, 1904 dates, merges, column widths, and style-table
// references.
#[test]
fn normalizes_xlsx_values_dates_formulas_merges_and_formats() {
    let document = CalamineReader.read(&fixture("reader.xlsx"), ReaderOptions::default());

    assert!(document.ok, "{:?}", document.error);
    assert!(document.warnings.is_empty());
    assert_eq!(document.sheets.len(), 1);
    let sheet = &document.sheets[0];
    assert_eq!(sheet.name, "Reader");
    assert_eq!((sheet.rows, sheet.cols), (4, 7));
    assert_eq!(sheet.merges, ["A3:B3", "D3:F4"]);
    assert_eq!(sheet.cells.len(), 15);
    assert_eq!(
        sheet.col_infos,
        [
            ColInfo { c: 0, width: 12.5 },
            ColInfo { c: 1, width: 20.0 },
            ColInfo { c: 2, width: 20.0 },
            ColInfo { c: 3, width: 20.0 },
            ColInfo { c: 6, width: 15.25 },
        ]
    );
    assert_eq!(
        document.styles,
        [
            CellStyle {
                bold: true,
                italic: true,
                underline: true,
                strike: true,
                font_size: Some(13.5),
                font_name: Some("Aptos Display".to_owned()),
                font_color: Some("#1A2B3C".to_owned()),
                fill_color: Some("#EEDDCC".to_owned()),
            },
            CellStyle {
                font_color: Some("#969696".to_owned()),
                fill_color: Some("#9999FF".to_owned()),
                ..CellStyle::default()
            },
        ]
    );

    assert_eq!(
        cell(&sheet.cells, 0, 0).v,
        Some(CellValue::Text("Hello shared".to_owned()))
    );
    assert_eq!(
        cell(&sheet.cells, 0, 5).v,
        Some(CellValue::Text("Rich text".to_owned()))
    );
    assert_eq!(cell(&sheet.cells, 0, 1).t, CellType::B);
    assert_eq!(cell(&sheet.cells, 0, 1).v, Some(CellValue::Bool(true)));
    assert_eq!(cell(&sheet.cells, 0, 2).t, CellType::E);
    assert_eq!(
        cell(&sheet.cells, 0, 2).v,
        Some(CellValue::Text("#DIV/0!".to_owned()))
    );

    let custom_date = cell(&sheet.cells, 0, 3);
    assert_eq!(custom_date.t, CellType::D);
    assert_eq!(
        custom_date.v,
        Some(CellValue::Text("1904-01-01".to_owned()))
    );
    assert_eq!(custom_date.fmt.as_deref(), Some("yyyy-mm-dd"));
    assert_eq!(custom_date.s, Some(0));
    let builtin_date = cell(&sheet.cells, 0, 4);
    assert_eq!(
        builtin_date.v,
        Some(CellValue::Text("1904-01-02".to_owned()))
    );
    assert_eq!(builtin_date.fmt.as_deref(), Some("mm-dd-yy"));
    assert_eq!(builtin_date.s, Some(0), "duplicate styles share one id");
    assert_eq!(cell(&sheet.cells, 0, 6).fmt.as_deref(), Some("#,##0.00"));
    assert_eq!(cell(&sheet.cells, 0, 6).s, Some(1));
    assert_eq!(
        cell(&sheet.cells, 1, 6).fmt.as_deref(),
        Some("0.0000 \"widgets\"")
    );
    assert_eq!(
        cell(&sheet.cells, 1, 6).s,
        None,
        "theme-only style becomes fully default"
    );

    let numeric_formula = cell(&sheet.cells, 1, 2);
    assert_eq!(numeric_formula.f.as_deref(), Some("SUM(A2:B2)"));
    assert_eq!(numeric_formula.v, Some(CellValue::Number(5.0)));
    let string_formula = cell(&sheet.cells, 1, 3);
    assert_eq!(string_formula.f.as_deref(), Some("CONCAT(\"x\",\"y\")"));
    assert_eq!(string_formula.v, Some(CellValue::Text("xy".to_owned())));

    let declared_uncached = cell(&sheet.cells, 1, 4);
    assert_eq!(declared_uncached.t, CellType::N);
    assert_eq!(declared_uncached.v, None);
    assert_eq!(declared_uncached.f.as_deref(), Some("A2/0"));
    let undeclared_uncached = cell(&sheet.cells, 1, 5);
    assert_eq!(undeclared_uncached.t, CellType::S);
    assert_eq!(undeclared_uncached.v, None);
    assert_eq!(undeclared_uncached.f.as_deref(), Some("UNSUPPORTED()"));
}

